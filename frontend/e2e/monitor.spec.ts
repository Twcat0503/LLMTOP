import { test, expect } from '@playwright/test';

test('shared snapshot, filters, details, pause, navigation, responsive layout', async ({ page, request }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('/');
  await expect(page).toHaveTitle('LLMTOP');
  await expect(page.getByRole('heading', { name: 'Overview', exact: true })).toBeVisible();
  await expect(page.getByText('Demo data', {exact: true})).toBeVisible();
  await expect(page.locator('.services-table tbody tr')).toHaveCount(3);
  await expect(page.getByText('Connected', {exact: true})).toBeVisible();
  const api = await (await request.get('/api/v1/snapshot')).json();
  const atlas = api.services.find((s: {id: string}) => s.id === 'atlas-vllm');
  const cells = page.locator('.services-table tbody tr').filter({hasText: 'atlas-vllm'}).locator('td');
  await expect(cells.nth(3)).toHaveText(atlas.metrics.input_tps.value.toFixed(1));
  await expect(cells.nth(5)).toHaveText(String(atlas.metrics.engine_running_requests.value));
  await page.getByLabel('Search services', {exact: true}).fill('workbench');
  await expect(page.locator('.services-table tbody tr')).toHaveCount(1);
  await page.locator('.services-table').getByRole('button', {name: 'workbench-llama', exact: true}).click();
  await expect(page.getByRole('dialog')).toContainText('No verified native KV occupancy metric');
  await expect(page.getByRole('dialog')).toContainText('epoch');
  await page.getByLabel('Trend metric').selectOption('kv_cache_usage_ratio');
  await expect(page.getByRole('dialog').getByRole('heading', {name: 'KV cache (%)', exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Close details'}).click();
  await page.getByLabel('Search services', {exact: true}).fill('nothing-matches');
  await expect(page.getByText('No services match these filters.')).toBeVisible();
  await page.getByLabel('Search services', {exact: true}).fill('');
  await page.getByLabel('Filter engine').selectOption('vllm');
  await expect(page.locator('.services-table tbody tr')).toHaveCount(2);
  await page.getByLabel('Filter engine').selectOption('all');
  await page.getByRole('button', {name: 'Output t/s', exact: true}).click();
  await expect(page.locator('th[aria-sort="descending"]')).toBeVisible();
  await page.getByRole('button', {name: 'Pause', exact: true}).click();
  await expect(page.getByRole('status')).toHaveText('Paused · collector continues');
  const frozen = await page.locator('.services-table tbody').innerText();
  await page.waitForTimeout(2300);
  expect(await page.locator('.services-table tbody').innerText()).toBe(frozen);
  await page.getByRole('button', {name: 'Resume', exact: true}).click();
  await expect(page.getByText('Paused · collector continues')).toHaveCount(0);
  await page.getByRole('button', {name: 'Hosts', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Host resources'})).toBeVisible();
  await expect(page.locator('.services-table')).toHaveCount(0);
  await page.getByRole('button', {name: 'Overview', exact: true}).click();
  await page.getByRole('button', {name: 'Refresh', exact: true}).click();
  const width = await page.evaluate(() => ({body: document.documentElement.scrollWidth, viewport: window.innerWidth}));
  expect(width.body).toBeLessThanOrEqual(width.viewport);
  await expect(page.locator('.chart text').first()).toBeVisible();
  const labelHeight = await page.locator('.chart text').first().evaluate(element => element.getBoundingClientRect().height);
  expect(labelHeight).toBeGreaterThan(10);
  await page.screenshot({path: `../artifacts/overview-${testInfo.project.name}.png`, fullPage: true});
  expect(errors).toEqual([]);
});

test('SSE outage falls back to existing snapshot reads', async ({page}) => {
  let requests = 0;
  await page.route('**/api/v1/events', route => route.abort());
  page.on('request', req => { if (req.url().endsWith('/api/v1/snapshot')) requests++; });
  await page.goto('/');
  await expect(page.locator('.services-table tbody tr')).toHaveCount(3);
  await expect(page.getByText('Reconnecting', {exact: true})).toBeVisible();
  await expect.poll(() => requests, {timeout: 6000}).toBeGreaterThan(1);
  await expect(page.locator('.services-table tbody tr')).toHaveCount(3);
});
